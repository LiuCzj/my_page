/**
 * 认证相关的所有有效期常量，集中在这一处。
 *
 * 【为什么单独开一个文件】
 * 2026-10-05 之前这些常量散在四个路由/模块里，而且**同一件事有两份**：
 * `forgot` 与 `reset` 各写了一份 `RESET_TTL_MS`，但只有 `reset` 那份真被用到 ——
 * 改 `forgot` 那份不会有任何效果，而两边的注释都写着「与对方保持一致」。
 * 这种「靠注释同步的常量」迟早会漂移，所以收成单一真相源：
 * 谁要用谁 import，不存在第二个可以改错的地方。
 *
 * 【为什么不做成环境变量】这几个值改动的代价是「用户手上的链接突然失效」，
 * 属于产品决策而不是运维参数；写死在代码里、跟着版本走，比放在 /etc 里更可控。
 *
 * 【本文件不允许有任何 import】保持零依赖，任何模块都能安全引用它，也不会成环。
 */

/**
 * 邮箱验证码（注册 / 注销）的有效期：10 分钟。
 * 够用户切到邮箱抄码，又不至于留着大半天。见 `lib/codes.ts`。
 */
export const EMAIL_CODE_TTL_MS = 10 * 60 * 1000;

/**
 * 找回密码 token 的有效期：1 小时。
 * 重置链接的杀伤力比验证链接大（能直接改密码），有效期越短，
 * 邮件在收件箱里躺久了被人翻出来利用的机会越小。见 `app/api/auth/reset/route.ts`。
 */
export const RESET_TTL_MS = 60 * 60 * 1000;

/**
 * 邮箱验证**链接**的有效期：24 小时。
 *
 * 【这是遗留链路的常量】2026-10-04 起注册改用 6 位验证码，不再产生新的验证链接，
 * 此值只服务于 `app/api/auth/verify/route.ts`（给历史未激活账号兜底）。
 * 详见该文件头部说明 —— 若要复活链接验证流程，先读那里列出的前置条件。
 */
export const VERIFY_TTL_MS = 24 * 60 * 60 * 1000;

/** 邮箱验证码有效期的分钟数（邮件正文与界面文案要写给人看，避免文案与常量各写一遍） */
export const EMAIL_CODE_TTL_MINUTES = EMAIL_CODE_TTL_MS / 60_000;

/** 重置链接有效期的小时数（同上：给文案用，别在字典里硬写「1」） */
export const RESET_TTL_HOURS = RESET_TTL_MS / 3_600_000;
